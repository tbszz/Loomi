export const LOCALE_STORAGE_KEY = 'loomi.locale';
const validLocale = locale => locale === 'en' || locale === 'zh';

export function readStoredLocale(storage) {
  try {
    const value = (storage ?? globalThis.localStorage)?.getItem(LOCALE_STORAGE_KEY);
    return validLocale(value) ? value : 'en';
  } catch { return 'en'; }
}

export function storeLocale(locale, storage) {
  if (!validLocale(locale)) return;
  try { (storage ?? globalThis.localStorage)?.setItem(LOCALE_STORAGE_KEY, locale); } catch { /* Storage denial must not block the UI. */ }
}

export function translate(locale, key, params = {}) {
  const dictionary = messages[validLocale(locale) ? locale : 'en'];
  const text = Object.hasOwn(dictionary, key) ? dictionary[key] : Object.hasOwn(messages.en, key) ? messages.en[key] : key;
  return text.replace(/\{(\w+)\}/g, (placeholder, name) => Object.hasOwn(params, name) ? String(params[name]) : placeholder);
}

export function createTranslator(locale = readStoredLocale()) {
  return (key, params) => translate(locale, key, params);
}

