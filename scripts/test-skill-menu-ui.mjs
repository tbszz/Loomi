import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright-core';
import { createDatabase } from '../server/database.js';
import { createApp } from '../server/app.js';

const directory = await mkdtemp(path.join(tmpdir(), 'resume-skill-menu-'));
const screenshots = process.env.SKILL_SCREENSHOTS || path.join(tmpdir(), 'resume-skill-menu-screenshots');
await mkdir(screenshots, { recursive: true });
const db = createDatabase({ filename: path.join(directory, 'test.sqlite') });
const model = async () => ({ content: [{ type: 'text', text: '已收到测试请求。' }] });
const port = 8895;
process.env.RESUME_PROTOCOL_PORT = String(port);
const server = createApp({ database: db, dataDir: directory, model, search: async () => ({ jobs: [], sources: [] }) }).listen(port, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
// Preserve Chinese regression coverage; default English is checked by test-workspace-ui.
  await context.addInitScript(() => { try { localStorage?.setItem("loomi.locale", "zh"); } catch {} });
  const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  assert((await context.request.post(`${base}/api/auth/register`, { data: { email: 'skills@example.test', name: 'Skill 测试', password: 'skill-menu-test-password' } })).ok());
  let releaseAuth;
  const authReady = new Promise(resolve => { releaseAuth = resolve; });
  await page.route('**/api/auth/me', async route => { await authReady; await route.continue(); });
  let catalogRequests = 0;
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/skills') catalogRequests++; });
  await page.goto(`${base}/#workspace`);
  await page.getByRole('heading', { name: '下一步，我们一起准备。' }).waitFor();
  const input = page.getByRole('textbox', { name: '给 Resume Protocol 发消息' });
  const menu = page.getByRole('listbox', { name: '可用 Skills' });
  const options = menu.getByRole('option');
  await input.fill('/');
  await page.getByText('请先登录，登录后可加载 Skills。', { exact: true }).waitFor();
  assert.equal(catalogRequests, 0, 'catalog does not race the initial auth request');
  releaseAuth();
  await options.nth(4).waitFor();
  assert(catalogRequests > 0, 'catalog loads when authenticated user resolves without a reload');
  await page.unroute('**/api/auth/me');
  await input.fill('');
  await page.getByRole('button', { name: '新建求职者' }).click();
  await page.getByRole('textbox', { name: '求职者名称' }).fill('Skill 测试候选人');
  await page.getByRole('button', { name: '创建', exact: true }).click();
  await page.getByRole('combobox', { name: '切换求职者' }).waitFor();
  const hasMenu = async () => assert.equal(await menu.count(), 1);
  const noMenu = async () => assert.equal(await menu.count(), 0);
  await input.fill('/');
  await options.nth(4).waitFor();
  assert.equal(await options.count(), 5);
  const second = await options.nth(1).locator('code').innerText();
  await input.press('ArrowDown');
  assert.equal(await options.nth(1).getAttribute('aria-selected'), 'true');
  assert.equal(await input.getAttribute('aria-activedescendant'), await options.nth(1).getAttribute('id'));
  await input.press('Enter');
  assert.equal(await input.inputValue(), `${second} `);
  await noMenu();
  assert.equal(await page.locator('.aui-message.user').count(), 0, 'selection must not send');
  await input.fill('/');
  await input.press('ArrowUp');
  assert.equal(await options.nth(4).getAttribute('aria-selected'), 'true');
  await input.press('Escape');
  await noMenu();
  assert.equal(await input.inputValue(), '/');
  await input.fill('/resume-analysis');
  assert.equal(await options.count(), 1);
  await input.press('Tab');
  assert.equal(await input.inputValue(), '/resume-analysis ');
  await input.fill('/简历');
  assert((await options.count()) >= 1, 'Chinese labels/descriptions are searchable');
  await options.nth(0).click();
  await noMenu();
  await input.fill('/not-a-skill');
  await page.getByText('没有匹配的 Skill。', { exact: true }).waitFor();
  await input.press('Enter');
  assert.equal(await page.locator('.aui-message.user').count(), 0);
  for (const text of ['https://example.test/resume', '/tmp/resume.txt', '请看 /resume', 'C:/resume']) {
    await input.fill(text);
    await noMenu();
  }
  await input.fill('/res 请核对项目\n和数字');
  await input.press('Control+Home');
  for (let index = 0; index < 4; index++) await input.press('ArrowRight');
  await hasMenu();
  await options.nth(0).click();
  assert.equal(await input.inputValue(), '/resume-analysis 请核对项目\n和数字');
  await page.mouse.move(0, 0);
  await input.fill('/');
  await page.waitForFunction(() => document.querySelectorAll('.aui-skill-options [role="option"]').length === 5 && document.querySelector('.aui-skill-options [role="option"]')?.getAttribute('aria-selected') === 'true');
  const imeSelection = await menu.locator('[aria-selected="true"] code').innerText();
  await input.evaluate(element => element.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true })));
  await input.press('Enter');
  assert.equal(await input.inputValue(), '/');
  assert.equal(await page.locator('.aui-message.user').count(), 0);
  await input.evaluate(element => element.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true })));
  await input.press('Tab');
  assert.equal(await input.inputValue(), `${imeSelection} `);
  await input.fill('/');
  await page.getByRole('button', { name: '新会话', exact: true }).click();
  await noMenu();
  assert.equal(await input.inputValue(), '', 'menu and command draft do not leak across conversations');
  let releaseRequest;
  const heldRequest = new Promise(resolve => { releaseRequest = resolve; });
  await page.route('**/api/conversations/*/messages', async route => {
    await heldRequest;
    await route.fulfill({ status: 503, json: { error: '测试请求已结束' } });
  });
  await input.fill('测试执行中禁用输入');
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.aui-composer-input')?.disabled);
  await noMenu();
  releaseRequest();
  await page.waitForFunction(() => !document.querySelector('.aui-composer-input')?.disabled);
  await page.unroute('**/api/conversations/*/messages');
  const sent = [];
  await page.route('**/api/conversations/*/messages', async route => {
    sent.push(route.request().postDataJSON());
    await route.fulfill({ status: 503, json: { error: '已记录测试请求' } });
  });
  await input.fill('普通消息仍可 Enter 发送');
  await input.press('Enter');
  await page.waitForFunction(() => !document.querySelector('.aui-composer-input')?.disabled && document.querySelector('.aui-composer-input')?.value === '');
  assert.equal(sent.length, 1, 'ordinary Enter sends exactly once');
  assert.match(JSON.stringify(sent[0]), /普通消息仍可 Enter 发送/);
  await input.fill('/resume-analysis');
  await input.press('Enter');
  assert.equal(sent.length, 1, 'skill selection must not send');
  await input.press('End');
  await page.keyboard.insertText('请分析我的简历');
  await input.press('Enter');
  await page.waitForFunction(() => !document.querySelector('.aui-composer-input')?.disabled && document.querySelector('.aui-composer-input')?.value === '');
  assert.equal(sent.length, 2, 'selected command sends exactly once when the task is submitted');
  assert.match(JSON.stringify(sent[1]), /\/resume-analysis 请分析我的简历/);
  await input.fill('第一行');
  await input.press('Shift+Enter');
  await page.keyboard.insertText('第二行');
  assert.equal(await input.inputValue(), '第一行\n第二行', 'Shift+Enter inserts a newline');
  assert.equal(sent.length, 2, 'Shift+Enter must not send');
  await input.evaluate(element => element.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true })));
  await input.press('Enter');
  assert.equal(sent.length, 2, 'IME confirmation must not send an ordinary message');
  // IME/browser interruptions can drop compositionend when focus leaves the input.
  await input.blur();
  await input.focus();
  const recoveredSend = page.waitForRequest(request => request.method() === 'POST' && /\/api\/conversations\/[^/]+\/messages$/.test(new URL(request.url()).pathname), { timeout: 3000 });
  await input.press('Enter');
  await recoveredSend;
  await page.waitForFunction(() => !document.querySelector('.aui-composer-input')?.disabled && document.querySelector('.aui-composer-input')?.value === '');
  assert.equal(sent.length, 3, 'Enter recovers after an interrupted IME composition loses focus');
  assert.match(JSON.stringify(sent[2]), /第一行\\n第二行/);
  await page.unroute('**/api/conversations/*/messages');
  for (const theme of ['亮色', '暗色']) {
    const button = page.getByRole('button', { name: theme, exact: true });
    if (await button.count()) await button.click();
    await input.fill('');
    await input.fill('/');
    await options.nth(4).waitFor();
    await page.screenshot({ path: path.join(screenshots, `${theme}-skills.png`) });
    const dimensions = await menu.boundingBox();
    const composer = await input.boundingBox();
    assert(dimensions.y + dimensions.height <= composer.y, 'menu is above the composer');
    await input.press('Escape');
  }
  await page.setViewportSize({ width: 375, height: 844 });
  await input.fill('');
  await input.fill('/');
  await options.nth(4).waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'narrow layout must not overflow');
  await page.screenshot({ path: path.join(screenshots, 'mobile-skills.png') });
  await page.route('**/api/skills', route => route.fulfill({ status: 503, json: { error: 'fixture catalog failure' } }));
  await page.reload();
  await input.fill('/');
  await page.getByText('Skills 加载失败，请重试。', { exact: false }).waitFor();
  assert.equal(await options.count(), 0, 'catalog failure must not invent skills');
  const messageCount = await page.locator('.aui-message.user').count();
  await input.press('Enter');
  assert.equal(await page.locator('.aui-message.user').count(), messageCount);
  await page.unroute('**/api/skills');
  await page.getByRole('button', { name: '重试加载 Skills', exact: true }).click();
  await options.nth(4).waitFor();
  assert(await input.evaluate(element => element === document.activeElement), 'retry preserves composer focus');
  assert.equal(await input.inputValue(), '/', 'retry preserves the draft');
  assert.equal(await page.locator('.aui-message.user').count(), messageCount, 'retry must not send');
  await page.route('**/api/skills', route => route.fulfill({ status: 401, json: { error: '请先登录。' } }));
  await page.reload();
  await input.fill('/');
  await page.getByText('请先登录，登录后可加载 Skills。', { exact: false }).waitFor();
  assert.equal(await options.count(), 0, 'expired authentication does not expose stale skills');
  await input.press('Enter');
  assert.equal(await page.locator('.aui-message.user').count(), messageCount, 'unauthenticated Enter does not send');
  await page.unroute('**/api/skills');
  await page.getByRole('button', { name: '重试加载 Skills', exact: true }).click();
  await options.nth(4).waitFor();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, screenshots, checks: ['auth-bootstrap', 'catalog', 'keyboard', 'aria', 'tab', 'escape', 'mouse', 'Chinese-filter', 'no-match', 'path-URL', 'suffix-preserved', 'IME', 'conversation-reset', 'busy-disabled', 'ordinary-submit', 'command-submit', 'shift-enter-newline', 'interrupted-IME-recovery', 'themes', 'mobile', 'catalog-error', 'catalog-retry', 'catalog-401-recovery'] }));
} catch (error) {
  await page.screenshot({ path: path.join(screenshots, 'failure.png') });
  console.error(JSON.stringify({ error: error.message, pageErrors: errors, body: await page.locator('body').innerText() }));
  throw error;
} finally {
  await browser.close();
  server.closeAllConnections();
  await new Promise(resolve => server.close(resolve));
  db.close();
  const resolved = path.resolve(directory);
  assert(resolved.startsWith(path.resolve(tmpdir()) + path.sep) && path.basename(resolved).startsWith('resume-skill-menu-'));
  await rm(resolved, { recursive: true, force: true });
}
